local scenario = require('tests.scenario')({ it = it })

describe('scenario: exploration views', function()
  scenario.test('log view shows recent commits', function(s)
    local main = s.world:repo('main', { ['file.txt'] = { 'base' } })
    s.world:write(main .. '/file.txt', { 'second' })
    s.world:commit(main, 'second commit')

    s.editor:cmd('cd ' .. main)
    s.editor:cmd('VGit log')
    s.editor:wait_for(function()
      return s.observe.contains(s, 'initial') or s.observe.contains(s, 'second commit')
    end, 'the log view to show commits')
    s.editor:settle()

    assert.is_truthy(s.observe.contains(s, 'second commit'))
    assert.is_truthy(s.observe.contains(s, 'initial'))
  end)

  scenario.test('blame view opens for a file', function(s)
    local main = s.world:repo('main', { ['file.txt'] = { 'base' } })

    s.editor:cmd('cd ' .. main)
    s.editor:cmd('edit file.txt')
    s.editor:settle()
    s.editor:cmd('VGit blame')
    s.editor:wait_for(function()
      return s.observe.contains(s, 'Scenario') or s.observe.contains(s, 'blame') or s.observe.contains(s, 'initial')
    end, 'the blame view to render')
    s.editor:settle()
  end)

  scenario.test('branch view lists branches', function(s)
    local main = s.world:repo('main', { ['file.txt'] = { 'base' } })
    s.world:git(main, 'checkout', '-b', 'feature-123')

    s.editor:cmd('cd ' .. main)
    s.editor:cmd('VGit branch')
    s.editor:wait_for(function()
      return s.observe.contains(s, 'feature-123')
    end, 'the branch view to list branches')
    s.editor:settle()
  end)
end)
